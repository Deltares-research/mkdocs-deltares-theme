"""Generate an installable MkDocs theme package from ``deltares/overrides``.

Usage:
    python build_package.py [--version 0.1.0] [--base material|materialx] [--wheel | --upload]

The package is written to ``build/mkdocs-deltares-theme``. With ``--wheel`` it is
also built into ``dist/`` (requires ``pip install build``). With ``--upload`` it is
built and pushed to the internal Nexus python-dev repository (also requires
``pip install twine``).

In a consuming repository, install the package and set in mkdocs.yml:

    theme:
      name: deltares
"""
import argparse
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).parent
SOURCE = ROOT / "deltares" / "overrides"
OUT = ROOT / "build" / "mkdocs-deltares-theme"
PACKAGE = "mkdocs_deltares_theme"

REPOSITORY_URL = "https://internal-artifacts.deltares.nl/repository/python-dev/"

BASE_REQUIREMENTS = {
    "material": "mkdocs-material>=9",
    "materialx": "mkdocs-materialx",
}

THEME_YML = """\
extends: {base}

logo: assets/logo-of-deltares.svg
favicon: assets/favicon-16x16.png
language: en
palette:
  - scheme: default
    primary: custom
    accent: custom
features:
  - navigation.tabs
  - navigation.tabs.sticky
  - navigation.expand
  - navigation.path
  - navigation.top
  - navigation.footer
  - search.suggest
  - search.highlight
  - content.code.copy
  - toc.integrate
"""

PYPROJECT = """\
[build-system]
requires = ["setuptools>=61"]
build-backend = "setuptools.build_meta"

[project]
name = "mkdocs-deltares-theme"
version = "{version}"
description = "Deltares theme for MkDocs, layered on top of {base}"
readme = "README.md"
requires-python = ">=3.8"
dependencies = ["{requirement}"]

[project.entry-points."mkdocs.themes"]
deltares = "{package}"

[tool.setuptools]
packages = ["{package}"]
include-package-data = true

[tool.setuptools.package-data]
{package} = ["*.yml", "*.html", "partials/**", "assets/**"]
"""

README = """\
# mkdocs-deltares-theme

Deltares theme for MkDocs. Install it and set in `mkdocs.yml`:

```yaml
theme:
  name: deltares
```

Generated by `build_package.py` from the mkdocs-deltares-theme repository.
"""


def generate(version: str, base: str) -> Path:
    if not SOURCE.is_dir():
        sys.exit(f"Source folder not found: {SOURCE}")
    if OUT.exists():
        shutil.rmtree(OUT)
    pkg = OUT / PACKAGE
    shutil.copytree(SOURCE, pkg)
    (pkg / "__init__.py").write_text("", encoding="utf-8")
    (pkg / "mkdocs_theme.yml").write_text(THEME_YML.format(base=base), encoding="utf-8")
    (OUT / "pyproject.toml").write_text(
        PYPROJECT.format(
            version=version, base=base, package=PACKAGE, requirement=BASE_REQUIREMENTS[base]
        ),
        encoding="utf-8",
    )
    (OUT / "README.md").write_text(README, encoding="utf-8")
    return OUT


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--version", default="0.1.0")
    parser.add_argument("--base", choices=BASE_REQUIREMENTS, default="material")
    parser.add_argument("--wheel", action="store_true", help="also build a wheel into dist/")
    parser.add_argument(
        "--upload",
        action="store_true",
        help=f"build and upload to {REPOSITORY_URL} (needs TWINE_USERNAME/TWINE_PASSWORD)",
    )
    args = parser.parse_args()

    out = generate(args.version, args.base)
    print(f"Package generated in {out}")
    if args.wheel or args.upload:
        dist = ROOT / "dist"
        if dist.exists():
            shutil.rmtree(dist)
        subprocess.run([sys.executable, "-m", "build", "--outdir", str(dist), str(out)], check=True)
    if args.upload:
        subprocess.run(
            [sys.executable, "-m", "twine", "upload", "--repository-url", REPOSITORY_URL]
            + [str(p) for p in sorted(dist.iterdir())],
            check=True,
        )


if __name__ == "__main__":
    main()
